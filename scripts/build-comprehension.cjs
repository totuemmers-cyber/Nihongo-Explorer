/* Reproducible packaging of original, manually authored learning material. */
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const units = [];
for (const level of ['N5', 'N4', 'N3', 'N2', 'N1']) {
  const counts = { reading: 0, listening: 0 };
  function add(skill, title, objective, texts, translation, glossary, note, questions) {
    const order = ++counts[skill], id = `${skill}-${level.toLowerCase()}-${order}`;
    const step = (order - 1) % 5;
    // Authored glossary readings also provide optional ruby for higher-level key terms.
    if (!/^N[45]$/.test(level)) {
      const terms = glossary.map(g => /^([^（]+)（([^）]+)）$/.exec(g[0])).filter(Boolean);
      texts = texts.map(text => terms.reduce((s, term) => s.split(term[1]).join(`{${term[1]}|${term[2]}}`), text));
    }
    const passages = texts.map((text, i) => {
      const match = /^([AB]): (.*)$/s.exec(text);
      return { id: `${id}-p${i + 1}`, speaker: match ? match[1] : '', text: match ? match[2] : text };
    });
    const unit = { id, level, skill, order, title, objective, minutes: (6 - Number(level[1])) * 2 + 5 + step,
      introduction: [
        'Orientiere dich zuerst: Wer spricht oder schreibt, und worum geht es? Bearbeite dann die drei Fragen.',
        'Achte zuerst auf das Ziel, dann auf Zeiten, Gründe und Einschränkungen. Beantworte alle drei Fragen.',
        'Halte Hauptaussage und wichtige Details auseinander. Prüfe deine Antworten vor der Auswertung.',
        'Verbinde Informationen aus mehreren Stellen. Nutze Hilfen erst, wenn du allein nicht weiterkommst.',
        'Arbeite möglichst selbstständig. Begründe deine Auswahl gedanklich mit einer konkreten Textstelle.'
      ][step], passages, translation, glossary, note,
      questions: questions.map((q, i) => {
        const [prompt, evidenceIndex, ...pairs] = q;
        const answer = (order + i + Number(level[1]) + (skill === 'listening' ? 1 : 0)) % 4;
        const choices = pairs.map(([text, explanation]) => ({ text, explanation, evidence: passages[evidenceIndex].id }));
        choices.splice(answer, 0, choices.shift());
        return { id: `${id}-q${i + 1}`, kind: ['global', 'detail', 'inference'][i], prompt, evidence: passages[evidenceIndex].id, choices, answer };
      })
    };
    if (skill === 'listening') unit.audio = { src: `audio/comprehension/${id}.wav`, synthetic: true, revision: 'native16-v3' };
    units.push(unit);
  }
  require(`./comprehension/${level.toLowerCase()}.cjs`)(add);
}
fs.writeFileSync(path.join(root, 'comprehension-data.js'), '/* Original guided units. Generated by scripts/build-comprehension.cjs. */\nwindow.COMPREHENSION_UNITS = ' + JSON.stringify(units, null, 2) + ';\n');
// Kana substitutions are the reviewed speech readings; the written transcript is retained above.
const readings = { '四日勤務': 'よっかきんむ', '一時半': 'いちじはん', '一時': 'いちじ', '二時': 'にじ', '十一時': 'じゅういちじ', '三十分': 'さんじゅっぷん', '一枚': 'いちまい', '二日': 'ふつか', '二部署': 'にぶしょ', '八割': 'はちわり', '百人': 'ひゃくにん', '六十人': 'ろくじゅうにん', '七十人': 'ななじゅうにん', '二千円': 'にせんえん', '十五分': 'じゅうごふん', '桜町': 'さくらまち', '一階': 'いっかい', '二階': 'にかい', '一週間': 'いっしゅうかん', '一時間': 'いちじかん', '一人': 'ひとり' };
const plain = text => {
  let speech = text.replace(/\{([^|]+)\|([^}]+)\}/g, '$2');
  for (const key of Object.keys(readings).sort((a, b) => b.length - a.length)) speech = speech.split(key).join(readings[key]);
  return speech;
};
const manifest = units.filter(u => u.audio).map(u => ({ id: u.id, src: u.audio.src, level: u.level, speakingRate: ({ N5: 0.75, N4: 0.83, N3: 0.91, N2: 1, N1: 1.08 })[u.level], pauseMs: ({ N5: 850, N4: 700, N3: 550, N2: 450, N1: 350 })[u.level], segments: u.passages.flatMap(p => p.text.split('\n').map((line, i) => {
  const match = /^([AB]): (.*)$/.exec(line), speaker = match ? match[1] : p.speaker;
  return { voice: speaker === 'B' ? 'Microsoft Ichiro' : 'Microsoft Haruka', text: plain(match ? match[2] : line) };
})) }));
fs.writeFileSync(path.join(root, 'audio-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(`Built ${units.length} units, ${units.reduce((n, u) => n + u.questions.length, 0)} questions and ${manifest.length} audio specifications.`);
