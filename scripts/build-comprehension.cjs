/* Reproducible packaging of original, manually authored learning material. */
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const units = [];
// Units re-recorded after the native16-v3 library build; the revision busts browser caches.
const audioRevisions = { 'listening-n3-7': 'native16-v4' };
// Additional JLPT task formats (scripts/comprehension/formats.cjs). Standard units keep their original schema.
const FORMAT_INTRO = {
  'quick-response': 'Du hörst jeweils einen kurzen Satz. Wähle die Antwort, die im Gespräch direkt passt – ohne lange nachzudenken.',
  utterance: 'Lies die Situation und höre, was gesagt wird. Wähle, was man in dieser Situation sagt.',
  'info-search': 'Du suchst bestimmte Informationen. Lies zuerst die Fragen und suche dann gezielt im Text.',
  integrated: 'Zwei Texte behandeln dasselbe Thema. Vergleiche, worin sie übereinstimmen und worin sie sich unterscheiden.',
  long: 'Ein längerer Text. Verfolge den Gedankengang Absatz für Absatz, bevor du die Fragen beantwortest.'
};
const FORMAT_KIND = { 'quick-response': 'response', utterance: 'utterance', 'info-search': 'search', integrated: 'integrated' };
for (const level of ['N5', 'N4', 'N3', 'N2', 'N1']) {
  const counts = { reading: 0, listening: 0 };
  function task(format, skill, title, objective, texts, translation, glossary, note, questions) {
    if (format !== 'standard' && !FORMAT_INTRO[format]) throw new Error('Unknown format ' + format);
    const order = ++counts[skill], id = `${skill}-${level.toLowerCase()}-${order}`;
    const step = (order - 1) % 5;
    // Authored glossary readings also provide optional ruby for higher-level key terms.
    if (!/^N[45]$/.test(level)) {
      const terms = glossary.map(g => /^([^（]+)（([^）]+)）$/.exec(g[0])).filter(Boolean);
      texts = texts.map(text => terms.reduce((s, term) => s.split(term[1]).join(`{${term[1]}|${term[2]}}`), text));
    }
    const passages = texts.map((text, i) => {
      // "Text A: …" labels one of two compared texts; "A: …"/"B: …" marks a speaker.
      const label = /^(Text [AB]): (.*)$/s.exec(text);
      if (label) return { id: `${id}-p${i + 1}`, speaker: '', label: label[1], text: label[2] };
      const match = /^([AB]): (.*)$/s.exec(text);
      return { id: `${id}-p${i + 1}`, speaker: match ? match[1] : '', text: match ? match[2] : text };
    });
    const standardMinutes = (6 - Number(level[1])) * 2 + 5 + step;
    const minutes = format === 'standard' ? standardMinutes : format === 'long' ? standardMinutes + 6
      : format === 'integrated' ? 12 : format === 'info-search' ? 8 : 4 + questions.length;
    const unit = { id, level, skill, order, title, objective, minutes,
      introduction: format !== 'standard' ? FORMAT_INTRO[format] : [
        'Orientiere dich zuerst: Wer spricht oder schreibt, und worum geht es? Bearbeite dann die drei Fragen.',
        'Achte zuerst auf das Ziel, dann auf Zeiten, Gründe und Einschränkungen. Beantworte alle drei Fragen.',
        'Halte Hauptaussage und wichtige Details auseinander. Prüfe deine Antworten vor der Auswertung.',
        'Verbinde Informationen aus mehreren Stellen. Nutze Hilfen erst, wenn du allein nicht weiterkommst.',
        'Arbeite möglichst selbstständig. Begründe deine Auswahl gedanklich mit einer konkreten Textstelle.'
      ][step], passages, translation, glossary, note,
      questions: questions.map((q, i) => {
        const [prompt, evidenceIndex, ...pairs] = q;
        const answer = (order + i + Number(level[1]) + (skill === 'listening' ? 1 : 0)) % pairs.length;
        const choices = pairs.map(([text, explanation]) => ({ text, explanation, evidence: passages[evidenceIndex].id }));
        choices.splice(answer, 0, choices.shift());
        const kind = format === 'standard' ? ['global', 'detail', 'inference'][i] : format === 'long' ? ['global', 'detail', 'inference', 'inference'][i] : FORMAT_KIND[format];
        return { id: `${id}-q${i + 1}`, kind, prompt, evidence: passages[evidenceIndex].id, choices, answer };
      })
    };
    if (format !== 'standard') unit.format = format;
    if (skill === 'listening') unit.audio = { src: `audio/comprehension/${id}.wav`, synthetic: true, revision: audioRevisions[id] || 'native16-v3' };
    units.push(unit);
  }
  const add = (...args) => task('standard', ...args);
  require(`./comprehension/${level.toLowerCase()}.cjs`)(add);
  // Format units continue the per-skill numbering after the standard units (IDs stay stable).
  const formats = require('./comprehension/formats.cjs')[level] || [];
  for (const unit of formats) task(...unit);
}
fs.writeFileSync(path.join(root, 'comprehension-data.js'), '/* Original guided units. Generated by scripts/build-comprehension.cjs. */\nwindow.COMPREHENSION_UNITS = ' + JSON.stringify(units, null, 2) + ';\n');
// Kana substitutions are the reviewed speech readings; the written transcript is retained above.
const readings = { '四日勤務': 'よっかきんむ', '一時半': 'いちじはん', '一時': 'いちじ', '二時': 'にじ', '十一時': 'じゅういちじ', '三十分': 'さんじゅっぷん', '一枚': 'いちまい', '二日': 'ふつか', '二部署': 'にぶしょ', '八割': 'はちわり', '百人': 'ひゃくにん', '六十人': 'ろくじゅうにん', '七十人': 'ななじゅうにん', '二千円': 'にせんえん', '十五分': 'じゅうごふん', '十分の予定': 'じっぷんのよてい', '桜町': 'さくらまち', '一階': 'いっかい', '二階': 'にかい', '一週間': 'いっしゅうかん', '一時間': 'いちじかん', '一人': 'ひとり' };
const plain = text => {
  let speech = text.replace(/\{([^|]+)\|([^}]+)\}/g, '$2');
  for (const key of Object.keys(readings).sort((a, b) => b.length - a.length)) speech = speech.split(key).join(readings[key]);
  return speech;
};
const manifest = units.filter(u => u.audio).map(u => ({ id: u.id, src: u.audio.src, level: u.level, speakingRate: ({ N5: 0.75, N4: 0.83, N3: 0.91, N2: 1, N1: 1.08 })[u.level], pauseMs: ({ N5: 850, N4: 700, N3: 550, N2: 450, N1: 350 })[u.level], segments: u.passages.flatMap(p => p.text.split('\n').map((line, i) => {
  const match = /^([AB]): (.*)$/.exec(line), speaker = match ? match[1] : p.speaker;
  return { voice: speaker === 'B' ? 'Microsoft Ichiro' : 'Microsoft Haruka', text: plain(match ? match[2] : line) };
})) }));
fs.writeFileSync(path.join(root, 'audio-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(`Built ${units.length} units, ${units.reduce((n, u) => n + u.questions.length, 0)} questions and ${manifest.length} audio specifications.`);
