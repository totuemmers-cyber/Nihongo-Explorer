// English content layer. German stays the source: the German data files are never edited for
// a translation. Translations are authored per record in i18n/en/<dataset>.json, each record
// tagged with a hash of the German text it was made from, and this script bakes them into
// copies of the data files under en/ (same globals, same shape) plus en/manifest.js, which
// tells the browser (i18n.js contentSrc) which files to load in English.
//
// A record whose German changed after translation is stale: it is not applied (the German
// shows) until it is translated again. A dataset without any applied record gets no en/ file,
// so the German file loads. Field values in the copies keep their German field names
// (example.german holds the English sentence), so the code reads both languages alike.
//
//   node scripts/build-english.cjs                 write en/ (only changed files)
//   node scripts/build-english.cjs --check         fail if en/ is not what the sources give
//   node scripts/build-english.cjs status          coverage per dataset
//   node scripts/build-english.cjs extract <dataset> [--limit=N] [--level=N5] [--stale] [--out=file]
//        records to translate, as [{ key, context, de: { path: value } }]
//   node scripts/build-english.cjs apply <dataset> <file>...
//        store translator output [{ key, en: { path: value } }] in i18n/en/<dataset>.json
//
// Field paths: "notes", "examples[].german", "exampleDetails{}.meaning", "glossary[][1]".
// [] walks an array, {} the values of an object, [N] one array position. A value has the shape
// the path gives the German: an array path takes an array of the same length, null where the
// German has no value (an example without a cloze).
