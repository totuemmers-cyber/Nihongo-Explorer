const GRAMMAR_FILES = ['grammar-data.js', 'grammar-n2.js', 'grammar-n1.js', 'keigo-data.js'];

function byKey(list, keyFn) {
  const map = new Map();
  for (const item of list) {
    const key = String(keyFn(item));
    if (map.has(key)) throw new Error('Duplicate translation key ' + key);
    map.set(key, item);
  }
  return map;
}

// One record per line keeps diffs of translation batches readable.
function arrayJs(name, items) {
  return HEADER + 'window.' + name + ' = [\n' + items.map(item => JSON.stringify(item)).join(',\n') + '\n];\n';
}
function valueJs(name, value) {
  return HEADER + 'window.' + name + ' = ' + JSON.stringify(value, null, 1) + ';\n';
}

const LEVEL_NOTES = [
  [/^Geschätztes Level – keine Quelle bestätigt es\.$/, () => 'Estimated level – no source confirms it.'],
  [/^Lehrbuch: (.+), Lektion (\d+)(.*)$/, (m, book, lesson, rest) => 'Textbook: ' + book + ', lesson ' + lesson + rest],
  [/^JLPT-Wortliste \(J\. Waller\): (N\d)(.*)$/, (m, level, rest) => 'JLPT word list (J. Waller): ' + level + rest],
  [/^Abgeleitet von (.+)$/, (m, rest) => 'Derived from ' + rest],
  [/^Zusammensetzung: (.+)$/, (m, rest) => 'Compound: ' + rest],
  [/^Seltenes Wort laut Häufigkeitsdaten \(wordfreq\), daher kein Einsteigerwort$/, () => 'Rare word according to frequency data (wordfreq), so not a beginner word']
];
// Level notes are generated by scripts/build-vocab-runtime.cjs from fixed templates.
function englishLevelNote(note) {
  if (typeof note !== 'string') return note;
  const capped = / \(Quelle: ([^;]+); Änderung auf zwei Stufen begrenzt\)$/;
  for (const [re, fn] of LEVEL_NOTES) {
    const m = re.exec(note);
    if (m) return fn(...m).replace(capped, ' (source: $1; change limited to two levels)');
  }
  throw new Error('Unknown level note template: ' + note);
}

