const readSource = file => fs.readFileSync(path.join(ROOT, file), 'utf8');

function run(files, seed = {}, readFile = readSource) {
  const c = Object.assign({ console }, seed); c.window = c;
  for (const file of files) vm.runInNewContext(readFile(file), c, { filename: file });
  return c;
}

// --- Paths -------------------------------------------------------------------------------

function parsePath(spec) {
  return spec.split('.').map(part => {
    const m = /^(\w+)((?:\[\]|\{\}|\[\d+\])*)$/.exec(part);
    if (!m) throw new Error('Bad field path ' + spec);
    return { name: m[1], ops: (m[2].match(/\[\]|\{\}|\[\d+\]/g) || []) };
  });
}

function getPath(record, spec) {
  const segments = parsePath(spec);
  function walk(value, si, oi) {
    if (si === segments.length) return typeof value === 'string' ? value : null;
    const seg = segments[si];
    if (oi === -1) return walk(value && typeof value === 'object' ? value[seg.name] : undefined, si, 0);
    if (oi === seg.ops.length) return walk(value, si + 1, -1);
    const op = seg.ops[oi];
    if (op === '[]') return Array.isArray(value) ? value.map(v => walk(v, si, oi + 1)) : null;
    if (op === '{}') return value && typeof value === 'object' ? Object.values(value).map(v => walk(v, si, oi + 1)) : null;
    return Array.isArray(value) ? walk(value[Number(op.slice(1, -1))], si, oi + 1) : null;
  }
  return walk(record, 0, -1);
}

function setPath(record, spec, translated) {
  const segments = parsePath(spec);
  // Writes value at holder[key], continuing with op oi of segment si.
  function put(holder, key, si, oi, value) {
    if (value === null || value === undefined || !holder || typeof holder !== 'object') return;
    const seg = segments[si];
    if (oi === seg.ops.length) {
      if (si + 1 === segments.length) { holder[key] = value; return; }
      put(holder[key], segments[si + 1].name, si + 1, 0, value);
      return;
    }
    const container = holder[key], op = seg.ops[oi];
    if (op === '[]') value.forEach((v, i) => put(container, i, si, oi + 1, v));
    else if (op === '{}') Object.keys(container).forEach((k, i) => put(container, k, si, oi + 1, value[i]));
    else put(container, Number(op.slice(1, -1)), si, oi + 1, value);
  }
  put(record, segments[0].name, 0, 0, translated);
}

// Same nesting, same array lengths, strings where the German has strings.
function sameShape(de, en) {
  if (de === null) return en === null || en === undefined;
  if (typeof de === 'string') return typeof en === 'string' && (de === '' ? true : en.trim().length > 0);
  return Array.isArray(de) && Array.isArray(en) && de.length === en.length && de.every((d, i) => sameShape(d, en[i]));
}

function flatten(value, out = []) {
  if (typeof value === 'string') out.push(value);
  else if (Array.isArray(value)) value.forEach(v => flatten(v, out));
  return out;
}

const hasGerman = de => flatten(Object.values(de)).some(text => /[A-Za-zÄÖÜäöüß]/.test(text));

const hash = value => crypto.createHash('sha256').update(JSON.stringify(value)).digest('hex').slice(0, 16);

