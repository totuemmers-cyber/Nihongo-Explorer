function englishLinks(items) {
  const links = run(['comprehension-links.js']).COMPREHENSION_LINKS;
  const meaning = new Map(items.map(item => [item.id, item.meaning]));
  const entries = links.entries.map(entry => {
    const copy = entry.slice();
    if (meaning.has(entry[0])) copy[3] = meaning.get(entry[0]);
    return copy;
  });
  return HEADER + 'window.COMPREHENSION_LINKS = ' + JSON.stringify({ entries, passages: links.passages }) + ';\n';
}

function fieldsOf(dataset, key) {
  return typeof dataset.fields === 'function' ? dataset.fields(key) : dataset.fields;
}

function germanOf(dataset, key, record) {
  const de = {};
  for (const field of fieldsOf(dataset, key)) de[field] = getPath(record, field);
  return de;
}

// --- Overlays ----------------------------------------------------------------------------

function overlayPath(name) { return path.join(ROOT, OVERLAY_DIR, name + '.json'); }
function readOverlay(name, readFile) {
  try { return JSON.parse(readFile(OVERLAY_DIR + '/' + name + '.json')); } catch (e) {
    if (e.code === 'ENOENT') return {};
    throw new Error(OVERLAY_DIR + '/' + name + '.json: ' + e.message);
  }
}
function writeOverlay(name, overlay) {
  const sorted = {};
  for (const key of Object.keys(overlay).sort()) sorted[key] = overlay[key];
  fs.mkdirSync(path.dirname(overlayPath(name)), { recursive: true });
  // One record per line, as in the generated files.
  const body = Object.keys(sorted).map(key => JSON.stringify(key) + ': ' + JSON.stringify(sorted[key])).join(',\n');
  fs.writeFileSync(overlayPath(name), '{\n' + body + '\n}\n');
}

// Applies an overlay to freshly loaded German data. Returns coverage and the applied keys.
function applyOverlay(name, dataset, loaded, overlay) {
  const records = dataset.records(loaded);
  // Records without German text (only Japanese, numbers) need no translation.
  const needed = [...records].filter(([key, record]) => hasGerman(germanOf(dataset, key, record))).length;
  const report = { total: needed, applied: 0, stale: [], orphan: [], invalid: [] };
  const applied = new Set();
  for (const [key, entry] of Object.entries(overlay)) {
    const record = records.get(key);
    if (!record) { report.orphan.push(key); continue; }
    const de = germanOf(dataset, key, record);
    if (!entry || entry.src !== hash(de)) { report.stale.push(key); continue; }
    const fields = fieldsOf(dataset, key);
    const bad = fields.find(field => !sameShape(de[field], entry.en && entry.en[field]));
    if (bad) { report.invalid.push(key + ' (' + bad + ')'); continue; }
    for (const field of fields) setPath(record, field, entry.en[field]);
    if (dataset.derive) dataset.derive(record);
    applied.add(key);
    report.applied++;
  }
  report.applied = applied.size;
  return { report, applied };
}

// --- Build -------------------------------------------------------------------------------

function build(readFile = readSource) {
  const files = {}, manifest = {}, reports = {};
  for (const [name, dataset] of Object.entries(DATASETS)) {
    const loaded = readFile === readSource ? dataset.load() : dataset.load(readFile);
    const { report, applied } = applyOverlay(name, dataset, loaded, readOverlay(name, readFile));
    reports[name] = report;
    if (!applied.size) continue;
    const written = dataset.write(loaded, applied);
    for (const [file, text] of Object.entries(written)) files[OUT_DIR + '/' + file] = text;
    Object.assign(manifest, dataset.manifest || Object.fromEntries(Object.keys(written).map(file => [file, OUT_DIR + '/' + file])));
  }
  const sorted = {};
  for (const key of Object.keys(manifest).sort()) sorted[key] = manifest[key];
  files[MANIFEST] = HEADER + '// Content files with an English copy; i18n.js loads these instead of the German files.\n' +
    'window.NIHONGO_CONTENT_FILES = window.NIHONGO_CONTENT_FILES || {};\nwindow.NIHONGO_CONTENT_FILES.' + LANG + ' = ' +
    JSON.stringify(sorted, null, 1) + ';\n';
  return { files, reports };
}

function existingOutputs() {
  const dir = path.join(ROOT, OUT_DIR);
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter(f => f.endsWith('.js')).map(f => OUT_DIR + '/' + f);
}

function differences(files) {
  const stale = Object.keys(files).filter(file => {
    const target = path.join(ROOT, file);
    return !fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== files[file];
  });
  const extra = existingOutputs().filter(file => !files[file]);
  return { stale, extra };
}

function printReports(reports) {
  for (const [name, r] of Object.entries(reports)) {
    const parts = [name + ': ' + r.applied + '/' + r.total + ' translated'];
    if (r.stale.length) parts.push(r.stale.length + ' stale (German changed; shown in German): ' + r.stale.slice(0, 5).join(', ') + (r.stale.length > 5 ? ' …' : ''));
    if (r.orphan.length) parts.push(r.orphan.length + ' without a German record: ' + r.orphan.slice(0, 5).join(', '));
    if (r.invalid.length) parts.push(r.invalid.length + ' invalid: ' + r.invalid.slice(0, 5).join(', '));
    console.log(parts.join('; '));
  }
}

// --- Translator workflow -----------------------------------------------------------------

function option(args, name) {
  const arg = args.find(a => a.startsWith('--' + name + '='));
  return arg ? arg.slice(name.length + 3) : null;
}

function extract(name, args) {
  const dataset = DATASETS[name];
  if (!dataset) throw new Error('Unknown dataset ' + name + '; known: ' + Object.keys(DATASETS).join(', '));
  const records = dataset.records(dataset.load());
  const overlay = readOverlay(name, readSource);
  const level = option(args, 'level'), limit = Number(option(args, 'limit')) || Infinity;
  const includeStale = args.includes('--stale');
  const batch = [];
  for (const [key, record] of records) {
    if (batch.length >= limit) break;
    if (level && dataset.level && dataset.level(record) !== level) continue;
    const de = germanOf(dataset, key, record);
    const entry = overlay[key];
    if (entry && (entry.src === hash(de) || !includeStale)) continue;
    if (!hasGerman(de)) continue;
    batch.push({ key, context: dataset.context ? dataset.context(record) : undefined, de });
  }
  const out = option(args, 'out');
  const text = JSON.stringify(batch, null, 1) + '\n';
  if (out) fs.writeFileSync(out, text); else process.stdout.write(text);
  console.error(batch.length + ' ' + name + ' records to translate' + (out ? ' written to ' + out : ''));
}

// Japanese written in the German must survive in the English (warning: notes may drop a
// German-only remark on purpose).
function lostJapanese(de, en) {
  const kept = flatten(en).join('\n');
  return [...new Set(flatten(de).join('\n').match(JAPANESE) || [])].filter(run => !kept.includes(run));
}

function apply(name, files) {
  const dataset = DATASETS[name];
  if (!dataset) throw new Error('Unknown dataset ' + name);
  const records = dataset.records(dataset.load());
  const overlay = readOverlay(name, readSource);
  let stored = 0;
  const errors = [], warnings = [];
  for (const file of files) {
    const items = JSON.parse(fs.readFileSync(file, 'utf8'));
    if (!Array.isArray(items)) throw new Error(file + ': expected an array');
    for (const item of items) {
      const record = item && records.get(String(item.key));
      if (!record) { errors.push(file + ': unknown key ' + (item && item.key)); continue; }
      const de = germanOf(dataset, String(item.key), record);
      const fields = fieldsOf(dataset, String(item.key));
      const en = {};
      const bad = fields.filter(field => {
        const value = item.en ? item.en[field] : undefined;
        en[field] = value === undefined && de[field] === null ? null : value;
        return !sameShape(de[field], en[field]);
      });
      if (bad.length) { errors.push(item.key + ': shape differs from the German in ' + bad.join(', ')); continue; }
      const lost = lostJapanese(Object.values(de), Object.values(en));
      if (lost.length) warnings.push(item.key + ': Japanese not in the English: ' + lost.slice(0, 6).join(' '));
      overlay[item.key] = { src: hash(de), en };
      stored++;
    }
  }
  if (errors.length) {
    console.error(errors.join('\n'));
    throw new Error(errors.length + ' records rejected; nothing written');
  }
  writeOverlay(name, overlay);
  if (warnings.length) console.log('Review: ' + warnings.length + ' records drop Japanese text\n  ' + warnings.join('\n  '));
  console.log('Stored ' + stored + ' ' + name + ' translations in ' + OVERLAY_DIR + '/' + name + '.json. Run npm run build:english.');
}

function main(args) {
  const command = args[0];
  if (command === 'extract') return extract(args[1], args.slice(2));
  if (command === 'apply') return apply(args[1], args.slice(2));
  const { files, reports } = build();
  if (command === 'status') { printReports(reports); return; }
  const { stale, extra } = differences(files);
  const invalid = Object.values(reports).reduce((n, r) => n + r.invalid.length + r.orphan.length, 0);
  if (args.includes('--check')) {
    printReports(reports);
    if (stale.length || extra.length) {
      console.error('English content out of date: ' + stale.concat(extra).join(', ') + '. Run npm run build:english ' +
        '(also after npm run build:vocab-runtime or any edit of German content).');
      process.exit(1);
    }
    if (invalid) { console.error(invalid + ' translation records are invalid or orphaned.'); process.exit(1); }
    console.log('English content is up to date.');
    return;
  }
  for (const file of stale) {
    fs.mkdirSync(path.dirname(path.join(ROOT, file)), { recursive: true });
    fs.writeFileSync(path.join(ROOT, file), files[file]);
  }
  for (const file of extra) fs.unlinkSync(path.join(ROOT, file));
  printReports(reports);
  console.log(stale.length || extra.length ? 'Wrote ' + stale.join(', ') + (extra.length ? '; removed ' + extra.join(', ') : '') : 'English content already up to date.');
}

module.exports = { DATASETS, build, getPath, setPath, sameShape, hash, englishLevelNote };
if (require.main === module) {
  try { main(process.argv.slice(2)); } catch (e) { console.error(e.message); process.exitCode = 1; }
}
