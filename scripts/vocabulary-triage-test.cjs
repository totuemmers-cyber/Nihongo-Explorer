const assert=require('assert');
const {audit,prepare,verify}=require('./vocabulary-triage.cjs');
const {hash}=require('./vocabulary-correction-pipeline.cjs');
const levels=['N5','N4','N3','N2','N1'];
const items=levels.flatMap(level=>Array.from({length:25},(_,i)=>({id:level+':'+i,level,word:level+i,reading:'かな',romaji:'kana',meaning:'Test',type:'Nomen',category:'Test',pitch:null,examples:[{japanese:'かな',romaji:'kana',german:'Test'}]})));
items[0].examples.push({...items[0].examples[0]});
items[1].pitch=4;
items[2].verbGroup='invalid';
const plan={items,ledger:items.map(v=>({id:v.id,editorial:v.id.endsWith(':24')?'reviewed':'pending'}))};
const doc=prepare(plan,{items,evidence:false,preservedFiles:{}});
assert.equal(doc.roster.length,100);
assert.equal(verify(doc,{checkFiles:false}).unfinished,100);
assert.equal(hash(doc.roster),hash(prepare(plan,{items,evidence:false,preservedFiles:{}}).roster));
assert.equal(new Set(doc.roster.map(v=>v.id)).size,100);
for(const level of levels)assert.equal(doc.roster.filter(v=>v.level===level).length,20);
assert(!doc.roster.some(v=>v.id.endsWith(':24')));
assert(doc.roster.filter(v=>['N5:0','N5:1','N5:2'].includes(v.id)).every(v=>v.selection==='mechanical'));
assert.deepStrictEqual(audit(items).map(f=>f.kind).sort(),['exact-duplicate-example','impossible-pitch','invalid-conjugation-metadata'].sort());
const validExcluded={...items[3],verbGroup:null,conjugationKind:'excluded',conjugationReading:null,notes:null,pitchVariants:null};
assert.equal(audit([validExcluded]).length,0,'Normal nonverb exclusion and nullable optional fields are valid');
assert(audit([{...validExcluded,examples:[]}]).some(f=>f.kind==='malformed-field'));
assert(audit([{...validExcluded,type:'invented'}]).some(f=>f.kind==='malformed-field'));
assert(audit([{...validExcluded,verbGroup:'godan',conjugation:{verbGroup:'ichidan'}}]).some(f=>f.detail.includes('conflicts')));
assert.equal(audit([{...validExcluded,id:'a',word:'一期一会',reading:'いちごいちえ'},{...validExcluded,id:'b',word:'一期一会',reading:'いちごいちえ'}]).length,0,'Explicit app overlap is intentional');
const row=doc.roster[0];doc.observations.push({id:row.id,contentHash:row.contentHash,worker:row.worker,status:'uncertain',finding:'Needs external evidence',reviewer:'fixture'});
assert.equal(verify(doc,{checkFiles:false}).inspected,1);
const mutate=fn=>{const copy=JSON.parse(JSON.stringify(doc));fn(copy);assert.throws(()=>verify(copy,{checkFiles:false}));};
mutate(d=>d.observations[0].contentHash='stale');
mutate(d=>d.observations.push(d.observations[0]));
mutate(d=>d.observations[0].worker=99);
mutate(d=>d.observations[0].editorial='reviewed');
mutate(d=>d.roster[1]=d.roster[0]);
mutate(d=>d.roster[0].content.meaning='tampered');
mutate(d=>d.fixes=Array.from({length:26},(_,i)=>({id:String(i)})));
mutate(d=>d.fixes=[{id:row.id,beforeHash:'stale',afterHash:'new',authoringFile:'example',revisionId:'example'}]);
console.log('Vocabulary triage tests passed: deterministic stratified allocation, mechanical priority, snapshot binding, observation isolation and cap.');
